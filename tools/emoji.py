#!/usr/bin/env python3
"""Write src/emoji_data.rs from Unicode's emoji-test.txt.

Every fully-qualified emoji goes in, in Unicode's groups and order, except
the skin-tone variants and the Component group. Each is labelled by its
Unicode name. Where the old list had a short label the name does not
contain ("rofl"), it stays after the name, so the words typed to find an
emoji before still find it.

    python3 tools/emoji.py [emoji-test.txt]
"""

import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/emoji/emoji-test.txt")
OUT = Path(__file__).resolve().parent.parent / "src" / "emoji_data.rs"
GROUPS = {
    "Smileys & Emotion": "Smileys",
    "People & Body": "People",
    "Animals & Nature": "Animals",
    "Food & Drink": "Food",
    "Travel & Places": "Travel",
    "Activities": "Activities",
    "Objects": "Objects",
    "Symbols": "Symbols",
    "Flags": "Flags",
}
SKIN = re.compile("[\U0001f3fb-\U0001f3ff]")
LINE = re.compile(r"^[0-9A-F ]+; fully-qualified\s+# (\S+) E\d+\.\d+ (.+)$")


def old_labels() -> dict[str, str]:
    """The short labels of the list being replaced, by glyph without VS16."""
    if not OUT.exists():
        return {}
    pairs = re.findall(r'\("([^"]+)", "([^"]*)"\)', OUT.read_text())
    labels: dict[str, str] = {}
    for glyph, label in pairs:
        labels.setdefault(glyph.replace("️", ""), label)
    return labels


def main() -> None:
    old = old_labels()
    cats: dict[str, list[tuple[str, str]]] = {}
    group = ""
    version = ""
    for line in SRC.read_text().splitlines():
        if line.startswith("# Version:"):
            version = line.split(":", 1)[1].strip()
        elif line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
        elif group in GROUPS and (m := LINE.match(line)) and not SKIN.search(m[1]):
            name = m[2]
            short = old.get(m[1].replace("️", ""), "")
            if short and short.lower() not in name.lower():
                name = f"{name} · {short}"
            cats.setdefault(GROUPS[group], []).append((m[1], name.replace("\\", "\\\\").replace('"', '\\"')))
    total = sum(len(v) for v in cats.values())
    out = [
        f"// AUTO-GENERATED by tools/emoji.py from Unicode's emoji-test.txt (Emoji {version}).",
        f"// Do not edit by hand. {len(cats)} categories, {total} emoji.",
        "",
        "pub struct EmojiCat {",
        "    pub name: &'static str,",
        "    pub items: &'static [(&'static str, &'static str)],  // (glyph, label)",
        "}",
        "",
    ]
    for cat, items in cats.items():
        out.append(f"static {cat.upper()}: &[(&str, &str)] = &[")
        out += [f'    ("{g}", "{n}"),' for g, n in items]
        out += ["];", ""]
    out.append("pub static EMOJI_CATEGORIES: &[EmojiCat] = &[")
    out += [f'    EmojiCat {{ name: "{c}", items: {c.upper()} }},' for c in cats]
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{total} emoji in {len(cats)} categories, Emoji {version}")


if __name__ == "__main__":
    main()
